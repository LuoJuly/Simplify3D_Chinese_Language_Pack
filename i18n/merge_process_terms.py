def main():
    path = pathlib.Path(r"D:\Software_Development\Simplify3D\汉化包\zh_table.py")
    src = path.read_text(encoding="utf-8")
    keys = set(re.findall(r"\n    ['\"]((?:\\.|[^'\"\\])*)['\"]:", src))
    # unescape simple
    decoded = set()
    for k in keys:
        decoded.add(bytes(k, "utf-8").decode("unicode_escape") if "\\" in k else k)
    # the regex above is fragile for mixed quotes; import instead
    import sys
    sys.path.insert(0, r"D:\Software_Development\Simplify3D\汉化包")
    from zh_table import T
    lines = []
    skipped = 0
    for en, zh in EXTRA.items():
        if en in T:
            skipped += 1
            continue
        if sorted(re.findall(r"%\d+", en)) != sorted(re.findall(r"%\d+", zh)):
            raise SystemExit(f"placeholder mismatch: {en}")
        lines.append("    " + repr(en) + ": " + repr(zh) + ",")
    body = src.rstrip()
    if not body.endswith("}"):
        raise SystemExit("bad ending")
    body = body[:-1].rstrip()
    if not body.endswith(","):
        body += ","
    body += "\n" + "\n".join(lines) + "\n}\n"
    path.write_text(body, encoding="utf-8")
    print(f"added {len(lines)} skipped {skipped}")


if __name__ == "__main__":
    main()
